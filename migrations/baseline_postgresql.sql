CREATE FUNCTION public.fn_prevent_published_schedule_entry_edit() RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $function$
DECLARE
    v_schedule_id INTEGER;
    v_status      VARCHAR(12);
BEGIN
    IF TG_TABLE_NAME = 'exam_room_allocations' THEN
        SELECT ee.schedule_id INTO v_schedule_id
        FROM exam_entries ee
        WHERE ee.exam_entry_id = COALESCE(NEW.exam_entry_id, OLD.exam_entry_id);
    ELSE
        v_schedule_id := COALESCE(NEW.schedule_id, OLD.schedule_id);
    END IF;

    SELECT status INTO v_status
    FROM schedules
    WHERE schedule_id = v_schedule_id;

    IF v_status IN ('Published', 'Archived') THEN
        RAISE EXCEPTION 'Entries of a % schedule (schedule_id=%) are read-only; create a new version instead (SAF-4).',
            v_status, v_schedule_id;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$function$;
